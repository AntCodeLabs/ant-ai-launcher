import AppKit

/// Starts Claude Code (the CLI) in a new terminal window, in a folder, with a login's CLAUDE_CONFIG_DIR.
///
/// It writes a one-shot `.command` script and opens it with the terminal app. That needs no
/// Automation permission, and works with Terminal and iTerm. The script deletes itself once it starts.
enum TerminalLauncher {
    static var scriptsDir: URL {
        ConfigStore.shared.fileURL.deletingLastPathComponent().appendingPathComponent("terminal", isDirectory: true)
    }

    /// `extraArgs` go after the command, e.g. ["--continue"] or a prompt.
    static func launch(_ account: Account, workspace: Workspace?, config: LauncherConfig, extraArgs: [String] = [],
                       completion: @escaping (Error?) -> Void) {
        let fm = FileManager.default
        let terminalURL = URL(fileURLWithPath: (config.terminalAppPath as NSString).expandingTildeInPath)
        guard fm.fileExists(atPath: terminalURL.path) else {
            completion(LaunchError.appNotFound(terminalURL.path)); return
        }
        let folder = workspace?.expandedPath ?? fm.homeDirectoryForCurrentUser.path
        let title = ["Claude Code", account.name, workspace?.name].compactMap { $0 }.joined(separator: " · ")

        var lines = [
            "#!/bin/zsh -il",
            "# Generated by Clauncher. Deletes itself on start.",
            "rm -f -- \"$0\"",
            "cd -- \(shellQuote(folder)) || exec /bin/zsh -il",
            "printf '\\e]0;%s\\a' \(shellQuote(title))",
        ]
        if let dir = account.resolvedCLIConfigDir {
            lines.append("export CLAUDE_CONFIG_DIR=\(shellQuote(dir))")
        }
        // `command` skips aliases such as `alias claude='CLAUDE_CONFIG_DIR=~/.claude claude'` in .zshrc,
        // which would otherwise override this login's config dir.
        let cmd = config.claudeCommand.trimmingCharacters(in: .whitespaces)
        let args = extraArgs.map(shellQuote).joined(separator: " ")
        lines.append("command \(cmd.isEmpty ? "claude" : cmd)\(args.isEmpty ? "" : " " + args)")
        lines.append("exec /bin/zsh -il   # keep the window open in this folder after Claude Code exits")

        do {
            try fm.createDirectory(at: scriptsDir, withIntermediateDirectories: true)
            let url = scriptsDir.appendingPathComponent("claude-\(UUID().uuidString.prefix(8)).command")
            try (lines.joined(separator: "\n") + "\n").write(to: url, atomically: true, encoding: .utf8)
            try fm.setAttributes([.posixPermissions: 0o700], ofItemAtPath: url.path)

            let cfg = NSWorkspace.OpenConfiguration()
            cfg.activates = true
            // The script deletes itself as its first step, so its disappearance confirms Terminal ran it.
            // Terminal occasionally drops an open request; if so, ask once more.
            func attempt(_ tries: Int) {
                NSWorkspace.shared.open([url], withApplicationAt: terminalURL, configuration: cfg) { _, err in
                    DispatchQueue.main.async {
                        if let err { completion(err); return }
                        waitForStart(url, timeout: 6) { started in
                            if started { completion(nil) }
                            else if tries < 2 { attempt(tries + 1) }
                            else {
                                try? FileManager.default.removeItem(at: url)
                                completion(LaunchError.terminalDidNotStart)
                            }
                        }
                    }
                }
            }
            attempt(1)
        } catch {
            completion(error)
        }
    }

    private static func waitForStart(_ url: URL, timeout: TimeInterval, done: @escaping (Bool) -> Void) {
        let deadline = Date().addingTimeInterval(timeout)
        func check() {
            if !FileManager.default.fileExists(atPath: url.path) { done(true); return }
            if Date() > deadline { done(false); return }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.3, execute: check)
        }
        check()
    }

    /// Existing Claude Code config folders in the home folder (~/.claude, ~/.claude-work, …).
    static func detectedConfigDirs() -> [String] {
        let home = FileManager.default.homeDirectoryForCurrentUser
        let names = (try? FileManager.default.contentsOfDirectory(atPath: home.path)) ?? []
        return names
            .filter { $0 == ".claude" || ($0.hasPrefix(".claude-") && $0 != ".claude-worktrees") }
            .filter { var isDir: ObjCBool = false
                      return FileManager.default.fileExists(atPath: home.appendingPathComponent($0).path, isDirectory: &isDir) && isDir.boolValue }
            .sorted()
            .map { "~/\($0)" }
    }

    /// Selects the Terminal tab running on `tty` (e.g. "/dev/ttys003") and brings it forward.
    /// Uses AppleScript, so macOS asks once for permission to control Terminal.
    static func focusTerminalTab(tty: String) {
        let script = """
        tell application "Terminal"
            repeat with w in windows
                repeat with t in tabs of w
                    if tty of t is "\(tty)" then
                        set selected of t to true
                        set index of w to 1
                        activate
                        return
                    end if
                end repeat
            end repeat
            activate
        end tell
        """
        DispatchQueue.main.async {   // NSAppleScript must run on the main thread
            var err: NSDictionary?
            NSAppleScript(source: script)?.executeAndReturnError(&err)
            if let err { NSLog("Clauncher: focus Terminal tab failed: \(err)") }
        }
    }

    static func shellQuote(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}
