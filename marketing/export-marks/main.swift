// Exports the app icon and the shrimp/ant SVG paths for the marketing screenshots.
import AppKit
let out = CommandLine.arguments[1]
try! Brand.appIcon(pixels: 512).representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: out + "/icon.png"))
func svgPath(_ p: CGPath) -> String {
    var d = ""
    func f(_ v: CGFloat) -> String { String(format: "%.2f", v) }
    p.applyWithBlock { e in
        let pts = e.pointee.points
        switch e.pointee.type {
        case .moveToPoint: d += "M\(f(pts[0].x)) \(f(pts[0].y)) "
        case .addLineToPoint: d += "L\(f(pts[0].x)) \(f(pts[0].y)) "
        case .addQuadCurveToPoint: d += "Q\(f(pts[0].x)) \(f(pts[0].y)) \(f(pts[1].x)) \(f(pts[1].y)) "
        case .addCurveToPoint: d += "C\(f(pts[0].x)) \(f(pts[0].y)) \(f(pts[1].x)) \(f(pts[1].y)) \(f(pts[2].x)) \(f(pts[2].y)) "
        case .closeSubpath: d += "Z "
        @unknown default: break
        }
    }
    return d
}
let r = CGRect(x: 0, y: 0, width: 32, height: 32)
let js = "// Generated by marketing/make-screenshots.sh from Sources/Brand.swift and ShrimpMark.swift.\n"
    + "const SHRIMP = \"\(svgPath(Brand.shrimpPath(in: r)))\";\nconst ANT = \"\(svgPath(Brand.antPath(in: r)))\";\n"
try! js.write(toFile: out + "/marks.js", atomically: true, encoding: .utf8)
